const providerCounters: Record<string, number> = {}

export const MODELS: ModelInfo[] = RAW_MODELS.map((model) => {
  const index = providerCounters[model.provider] ?? 0
  providerCounters[model.provider] = index + 1
  const palette = PROVIDER_PALETTES[model.provider] ?? PALETTE

  return {
    ...model,
    color: palette[index % palette.length],
    dash: index >= palette.length ? [6, 4] : undefined,
  }
})

